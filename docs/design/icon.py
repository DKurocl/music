"""Generate the launcher and startup resources from one Music mark."""

from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RES = ROOT / "app/src/main/res/drawable"
HEADER = '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by docs/design/icon.py; edit the script. -->\n'
ANDROID = 'xmlns:android="http://schemas.android.com/apk/res/android"'
AAPT = 'xmlns:aapt="http://schemas.android.com/aapt"'
SIZE = 'android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108"'
COLORS = ("#CD6654", "#B34A3B")
DURATION = 460
MARK_SCALE = 0.68
MARK_X = 0.8
MARK_Y = -2.0
# An offset pair of note heads and their connecting beam, as one outline.
MARK = ("M43,60 V38 Q43,34 47,33 L73,27 Q78,26 78,31 V64 "
        "C78,71 71,76 64,76 C58,76 54,72 55,67 C56,61 63,57 71,58 "
        "V40 L50,45 V75 C50,82 43,87 36,87 C30,87 26,83 27,78 "
        "C28,72 35,68 43,69 Z")


def draw(animated=False, themed=False):
    paint = ('android:fillColor="#FFFFFFFF"' if themed else "")
    gradient = "" if themed else (
        '<aapt:attr name="android:fillColor"><gradient android:type="linear" '
        'android:startX="68" android:startY="31" android:endX="34" android:endY="86">'
        f'<item android:offset="0" android:color="{COLORS[0]}"/>'
        f'<item android:offset="1" android:color="{COLORS[1]}"/>'
        '</gradient></aapt:attr>'
    )
    name = 'android:name="mark"' if animated else ""
    return (f'<group {name} android:pivotX="54" android:pivotY="54">'
            f'<group android:pivotX="54" android:pivotY="54" android:scaleX="{MARK_SCALE}" '
            f'android:scaleY="{MARK_SCALE}" android:translateX="{MARK_X}" android:translateY="{MARK_Y}"><path {paint} android:pathData="{MARK}">'
            f'{gradient}</path></group></group>')


def animator(prop, start, end):
    return (f'<objectAnimator android:propertyName="{prop}" android:duration="{DURATION}" '
            f'android:valueType="floatType" android:valueFrom="{start}" android:valueTo="{end}" '
            'android:interpolator="@interpolator/w_emphasized"/>')


def write(name, value):
    (RES / name).write_text(HEADER + value + "\n", encoding="utf-8")


def main():
    write("ic_launcher_foreground.xml", f'<vector {ANDROID} {AAPT} {SIZE}>{draw()}</vector>')
    write("ic_launcher_background.xml", f'<shape {ANDROID}><solid android:color="#FFFFFFFF"/></shape>')
    write("ic_launcher_monochrome.xml", f'<vector {ANDROID} {SIZE}>{draw(themed=True)}</vector>')
    motion = animator("scaleX", 0.78, 1) + animator("scaleY", 0.78, 1) + animator("translationY", 6, 0)
    write("splash_icon.xml", f'<animated-vector {ANDROID} {AAPT}><aapt:attr name="android:drawable">'
          f'<vector {SIZE}>{draw(animated=True)}</vector></aapt:attr>'
          f'<target android:name="mark"><aapt:attr name="android:animation"><set>{motion}</set></aapt:attr></target>'
          '</animated-vector>')

    path = f'<path d="{MARK}" transform="translate({54 + MARK_X} {54 + MARK_Y}) scale({MARK_SCALE}) translate(-54 -54)"'
    panels = [
        '<circle cx="54" cy="54" r="36" fill="white"/>' + f'{path} fill="url(#g)"/>',
        '<rect x="18" y="18" width="72" height="72" rx="22" fill="white"/>' + f'{path} fill="url(#g)"/>',
        '<circle cx="54" cy="54" r="36" fill="#2b2a33"/>' + f'{path} fill="#d0bcff"/>',
        f'{path} fill="url(#g)"/>',
    ]
    svg = ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 312 72" width="1248" height="288">'
           '<defs><linearGradient id="g" x1="68" y1="31" x2="34" y2="86" gradientUnits="userSpaceOnUse">'
           f'<stop stop-color="{COLORS[0]}"/><stop offset="1" stop-color="{COLORS[1]}"/></linearGradient></defs>'
           '<rect width="312" height="72" fill="#1b1b21"/>')
    svg += "".join(f'<g transform="translate({i * 80 - 18} -18)">{panel}</g>' for i, panel in enumerate(panels))
    (ROOT / "docs/design/icon-preview.svg").write_text(svg + "</svg>\n", encoding="utf-8")


if __name__ == "__main__":
    main()
