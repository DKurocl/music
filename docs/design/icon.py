"""Generate Music's adaptive launch icon from the approved Play and note artwork."""

from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DRAWABLES = ROOT / "app/src/main/res/drawable"
HEADER = '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by docs/design/icon.py; edit the script. -->\n'
ANDROID = 'xmlns:android="http://schemas.android.com/apk/res/android"'
AAPT = 'xmlns:aapt="http://schemas.android.com/aapt"'
SIZE = 'android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108"'

# The Play wedge carries more visual weight on the left. Bias it to the right inside the circle.
ART_SCALE = 0.055
ART_X = 21.75
ART_Y = 17.95
BACKGROUND = "#FFFDFE"
PLAY = ("M235,385 C235,302 254,261 309,225 C366,188 419,197 473,226 "
        "L982,527 C1041,562 1069,603 1069,658 C1069,711 1043,747 988,783 "
        "L442,1081 C387,1111 335,1103 292,1075 C250,1047 235,1000 235,939 Z")
LIP = ("M432,1039 L1002,708 L1022,758 C1013,810 989,840 940,868 L582,1069 "
       "C526,1101 479,1093 441,1062 Z")
NOTE = ("M462,766 L462,528 C462,491 478,466 510,454 L774,385 "
        "C825,370 862,393 865,449 L862,744 C862,806 829,844 788,862 "
        "C741,882 687,863 659,827 C628,786 643,730 674,694 "
        "C706,659 750,650 794,665 L795,499 L546,567 Q530,572 530,589 "
        "L530,812 C530,864 496,909 449,930 C401,951 350,936 323,902 "
        "C295,868 309,813 343,776 C377,740 421,719 462,735 Z")
PLAY_STOPS = ((0.0, "#FFCB00"), (0.36, "#FFA412"), (0.62, "#FF6536"), (1.0, "#F551C6"))
LIP_STOPS = ((0.0, "#FCE6AF"), (1.0, "#FAD1EF"))
NOTE_STOPS = ((0.0, "#FFFFFF"), (1.0, "#FFF0F2"))
PLAY_AXIS = ((264, 385), (1010, 785))
LIP_AXIS = ((600, 1080), (976, 834))
NOTE_AXIS = ((465, 458), (833, 833))
DURATION = 340
NOTE_DELAY = 64


def gradient(name, path, stops, axis, alpha=1):
    (x1, y1), (x2, y2) = axis
    stops_xml = "".join(f'<item android:offset="{offset}" android:color="{color}"/>' for offset, color in stops)
    return (f'<path android:name="{name}" android:pathData="{path}" android:fillAlpha="{alpha}">'
            f'<aapt:attr name="android:fillColor"><gradient android:type="linear" '
            f'android:startX="{x1}" android:startY="{y1}" android:endX="{x2}" android:endY="{y2}">'
            f'{stops_xml}</gradient></aapt:attr></path>')


def art_group(content):
    return (f'<group android:scaleX="{ART_SCALE}" android:scaleY="{ART_SCALE}" '
            f'android:translateX="{ART_X}" android:translateY="{ART_Y}">{content}</group>')


def vector(themed=False, animated=False):
    if themed:
        mask = f"M0,0 H1280 V1280 H0 Z {NOTE}"
        content = (f'<clip-path android:pathData="{PLAY}"/>'
                   f'<path android:fillColor="#FFFFFFFF" android:fillType="evenOdd" android:pathData="{mask}"/>')
        return art_group(content)
    play = gradient("lip", LIP, LIP_STOPS, LIP_AXIS) + gradient("face", PLAY, PLAY_STOPS, PLAY_AXIS)
    note = gradient("note_face", NOTE, NOTE_STOPS, NOTE_AXIS, alpha=0 if animated else 1)
    return ('<group android:name="mark" android:pivotX="54" android:pivotY="54">'
            + art_group(play + f'<group android:name="note" android:pivotX="652" android:pivotY="640">{note}</group>')
            + '</group>')


def animator(property_name, start, end, duration, delay=0):
    return (f'<objectAnimator android:propertyName="{property_name}" android:duration="{duration}" '
            f'android:startOffset="{delay}" android:valueType="floatType" android:valueFrom="{start}" '
            f'android:valueTo="{end}" android:interpolator="@interpolator/w_emphasized"/>')


def target(name, *motion):
    return (f'<target android:name="{name}"><aapt:attr name="android:animation"><set>'
            + "".join(motion) + '</set></aapt:attr></target>')


def write(name, markup):
    (DRAWABLES / name).write_text(HEADER + markup + "\n", encoding="utf-8")


def svg_defs():
    def paint(name, stops, axis):
        (x1, y1), (x2, y2) = axis
        items = "".join(f'<stop offset="{offset}" stop-color="{color}"/>' for offset, color in stops)
        return (f'<linearGradient id="{name}" x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}" '
                f'gradientUnits="userSpaceOnUse">{items}</linearGradient>')

    return ("<defs>" + paint("play", PLAY_STOPS, PLAY_AXIS) + paint("lip", LIP_STOPS, LIP_AXIS)
            + paint("note", NOTE_STOPS, NOTE_AXIS) + f'<clipPath id="play-mask"><path d="{PLAY}"/></clipPath></defs>')


def svg_mark(scale=1, note_y=0, note_scale=1, note_alpha=1, themed=False):
    fit = f"translate({ART_X} {ART_Y}) scale({ART_SCALE})"
    if themed:
        return (f'<g transform="{fit}" clip-path="url(#play-mask)">'
                f'<path d="M0,0 H1280 V1280 H0 Z {NOTE}" fill="#E1D2FF" fill-rule="evenodd"/></g>')
    return (f'<g transform="translate(54 54) scale({scale}) translate(-54 -54)">'
            f'<g transform="{fit}"><path d="{LIP}" fill="url(#lip)"/><path d="{PLAY}" fill="url(#play)"/>'
            f'<path d="{NOTE}" fill="url(#note)" opacity="{note_alpha}" '
            f'transform="translate(652 {640 + note_y}) scale({note_scale}) translate(-652 -640)"/></g></g>')


def main():
    write("ic_launcher_foreground.xml", f'<vector {ANDROID} {AAPT} {SIZE}>{vector()}</vector>')
    write("ic_launcher_background.xml", f'<shape {ANDROID}><solid android:color="{BACKGROUND}"/></shape>')
    write("ic_launcher_monochrome.xml", f'<vector {ANDROID} {SIZE}>{vector(themed=True)}</vector>')

    motion = (target("mark", animator("scaleX", 0.88, 1, 250), animator("scaleY", 0.88, 1, 250))
              + target("note", animator("translationY", -53, 0, DURATION - NOTE_DELAY, NOTE_DELAY),
                       animator("scaleX", 1.08, 1, DURATION - NOTE_DELAY, NOTE_DELAY),
                       animator("scaleY", 1.08, 1, DURATION - NOTE_DELAY, NOTE_DELAY))
              + target("note_face", animator("fillAlpha", 0, 1, 168, NOTE_DELAY)))
    write("splash_icon.xml", f'<animated-vector {ANDROID} {AAPT}><aapt:attr name="android:drawable">'
          f'<vector {SIZE}>{vector(animated=True)}</vector></aapt:attr>{motion}</animated-vector>')

    panels = [
        f'<circle cx="54" cy="54" r="36" fill="{BACKGROUND}"/>' + svg_mark(),
        f'<rect x="18" y="18" width="72" height="72" rx="22" fill="{BACKGROUND}"/>' + svg_mark(),
        '<circle cx="54" cy="54" r="36" fill="#322741"/>' + svg_mark(themed=True),
        svg_mark(),
    ]
    svg = ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 320 88" width="1280" height="352">'
           + svg_defs() + '<rect width="320" height="88" fill="#18151E"/>')
    svg += "".join(f'<g transform="translate({i * 80 - 14} -10)">{panel}</g>' for i, panel in enumerate(panels))
    (ROOT / "docs/design/icon-preview.svg").write_text(svg + "</svg>\n", encoding="utf-8")


if __name__ == "__main__":
    main()
